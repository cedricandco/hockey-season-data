-- =====================================================================
-- hockey-season-data — schéma PostgreSQL de référence (généré pour revue)
-- Vraie source de vérité : migrations EF Core (HockeySeason.Infrastructure)
-- Ce script sert de référence documentaire et de revue manuelle.
-- =====================================================================

CREATE TABLE organizations (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    external_id TEXT UNIQUE,               -- présent seulement si l'orga a un miroir Spordle
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE divisions (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    external_id     TEXT NOT NULL UNIQUE,  -- Spordle office id (6193, 6194)
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE seasons (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,             -- ex. « 2026-27 »
    external_id TEXT NOT NULL UNIQUE,      -- Spordle season id (« 2026-27 »)
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE leagues (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id  INT NOT NULL REFERENCES divisions(id) ON DELETE CASCADE,
    season_id    INT NOT NULL REFERENCES seasons(id) ON DELETE RESTRICT,
    name         TEXT NOT NULL,
    external_id  TEXT NOT NULL UNIQUE,     -- Spordle league id (194908)
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE teams (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id   INT NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    external_id TEXT NOT NULL UNIQUE,      -- Spordle team id
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Licences logicielles : COACH (5 équipes), DIRECTOR (5 ligues), PRESIDENT (association entière)
CREATE TABLE roles (
    id                    SMALLINT PRIMARY KEY,
    code                  TEXT NOT NULL UNIQUE,   -- coach | director | president
    name                  TEXT NOT NULL,
    max_followed_entities INT NOT NULL DEFAULT 0  -- 0 = pas de suivi individuel ; président via org
);

-- Utilisateurs Auth0 + facturation future (Stripe id rempli plus tard)
CREATE TABLE users (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth0_user_id      TEXT NOT NULL UNIQUE,          -- claim `sub` du JWT
    email              TEXT,
    first_name         TEXT,
    last_name          TEXT,
    stripe_customer_id TEXT,                          -- rempli plus tard par le webhook Stripe
    is_admin           BOOLEAN NOT NULL DEFAULT false,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_roles (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id    SMALLINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, role_id)
);

-- Une ligne par utilisateur : couleurs + extras génériques
CREATE TABLE user_settings (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    primary_color   TEXT,
    secondary_color TEXT,
    extra           JSONB NOT NULL DEFAULT '{}',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Suivi d'équipe. Verrou : modification (suppression) bloquée 15 jours après
-- l'ajout, sauf admin. unlock_requested_at sert de trace d'audit pour l'interface admin.
CREATE TABLE team_subscriptions (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    team_id             INT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_until        TIMESTAMPTZ NOT NULL,       -- created_at + 15 jours, calculé par l'application
    unlock_requested_at TIMESTAMPTZ,                -- demandé par l'utilisateur, traité par l'admin
    UNIQUE (user_id, team_id)
);

-- Suivi de ligue (rôle DIRECTOR) ; le PRESIDENT suit l'association entière.
CREATE TABLE league_subscriptions (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    league_id  INT NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, league_id)
);

