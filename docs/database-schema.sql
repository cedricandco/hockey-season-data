CREATE INDEX ix_teams_league ON teams(league_id);
CREATE INDEX ix_leagues_division ON leagues(division_id);
CREATE INDEX ix_leagues_season ON leagues(season_id);
CREATE INDEX ix_divisions_organization ON divisions(organization_id);
CREATE INDEX ix_team_subscriptions_user ON team_subscriptions(user_id);
CREATE INDEX ix_team_subscriptions_team ON team_subscriptions(team_id);
CREATE INDEX ix_league_subscriptions_user ON league_subscriptions(user_id);
CREATE INDEX ix_user_roles_user ON user_roles(user_id);
